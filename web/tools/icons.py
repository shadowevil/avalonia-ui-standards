#!/usr/bin/env python3
"""Write web/blocks/icons.js from the desktop Icons.cs (0026): python3 web/tools/icons.py

Each icon's SVG path data is copied verbatim, keyed by its Phosphor name (the library's own
icons by their property name in kebab-case), in the order Icons.cs declares them.
Run with --check to fail when icons.js is out of date instead of writing it.
"""
import re
import sys

import common

SOURCE = common.WEB.parent / "src" / "AvaloniaUiStandards" / "Blocks" / "Icons.cs"
TARGET = common.WEB / "blocks" / "icons.js"

ENTRY = re.compile(
    r'///\s*<summary>(?P<doc>.*?)</summary>\s*'
    r'public static Geometry (?P<prop>\w+) => field \?\?= Parse\("(?P<d>[^"]+)"\);')


def kebab(pascal):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", pascal).lower()


def generate():
    entries = []
    for m in ENTRY.finditer(SOURCE.read_text(encoding="utf-8")):
        phosphor = re.search(r"Phosphor <c>([a-z0-9-]+)</c>", m["doc"])
        entries.append((phosphor[1] if phosphor else kebab(m["prop"]), m["d"]))
    if not entries:
        sys.exit(f"No icons found in {SOURCE}")
    names = [n for n, _ in entries]
    if len(set(names)) != len(names):
        sys.exit("Duplicate icon names in Icons.cs")
    lines = [
        "// Generated by web/tools/icons.py from src/AvaloniaUiStandards/Blocks/Icons.cs; do not edit.",
        "// Phosphor Regular (MIT, see THIRD-PARTY-NOTICES.md) and the library's own icons in its style:",
        "// SVG path data in the 256 x 256 design box, nonzero fill rule (0026).",
        "export const icons = Object.freeze({",
        *[f'  "{n}": "{d}",' for n, d in entries],
        "});",
        "",
    ]
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            sys.exit(f"{TARGET.relative_to(common.WEB.parent)} is out of date; run python3 web/tools/icons.py")
        print("icons.js is up to date")
        return
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(common.WEB.parent)} ({text.count(chr(10)) - 5} icons)")


if __name__ == "__main__":
    main()
