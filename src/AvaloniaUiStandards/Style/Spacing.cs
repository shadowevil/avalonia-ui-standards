namespace AvaloniaUiStandards.Style;

/// <summary>
/// The 4 px spacing grid, shared by the <c>Spacing*</c> resources and the control themes
/// that need the values in code (for example to build a <see cref="Avalonia.Thickness"/>).
/// </summary>
internal static class Spacing
{
    public const double XS = 4;
    public const double S = 8;
    public const double M = 12;
    public const double L = 16;
    public const double XL = 24;
    public const double XXL = 32;
    public const double XXXL = 48;
}
